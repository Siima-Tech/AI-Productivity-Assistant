import { createFileRoute, Link } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { useState } from "react";
import { Sparkles } from "lucide-react";
import { Button } from "@/components/ui/button";
import { PageHeader } from "@/components/site/PageHeader";
import { ProductCard } from "@/components/site/ProductCard";
import { matchHeadline, productsQuery, recommend, type QuizAnswers } from "@/lib/products";
import { seo } from "@/lib/seo";
import { cn } from "@/lib/utils";

export const Route = createFileRoute("/find-your-scent")({
  head: () => seo("Find Your Signature Scent", "Answer five quick questions and our Candle Matchmaker recommends candles for your mood, room and budget."),
  component: Quiz,
});

const STEPS: { key: keyof QuizAnswers; q: string; options: { v: string; l: string }[] }[] = [
  { key: "mood", q: "What mood do you want to create?", options: ["relaxation", "romance", "freshness", "energy", "comfort"].map((v) => ({ v, l: v })) },
  { key: "room", q: "Where will you use your candle?", options: [
    { v: "bedroom", l: "Bedroom" }, { v: "bathroom", l: "Bathroom" }, { v: "living room", l: "Living room" }, { v: "office", l: "Office" }, { v: "gift", l: "As a gift" }] },
  { key: "family", q: "Which fragrance family do you prefer?", options: ["floral", "fresh", "sweet", "woody", "warm"].map((v) => ({ v, l: v })) },
  { key: "budget", q: "What is your budget?", options: [{ v: "under-250", l: "Under R250" }, { v: "250-400", l: "R250 – R400" }, { v: "any", l: "No limit" }] },
  { key: "forWhom", q: "Who is it for?", options: [{ v: "me", l: "Myself" }, { v: "someone", l: "Someone special" }] },
];

function Quiz() {
  const { data: products = [] } = useQuery(productsQuery);
  const [step, setStep] = useState(0);
  const [ans, setAns] = useState<Partial<QuizAnswers>>({});
  const done = step >= STEPS.length;
  const answers = ans as QuizAnswers;
  const results = done ? recommend(products, answers) : [];

  return (
    <>
      <PageHeader eyebrow="Candle Matchmaker" title="Find Your Signature Scent">
        Our matchmaker uses a transparent rule-based system that scores candles from our catalogue against your answers. You're always free to choose differently.
      </PageHeader>
      <div className="mx-auto max-w-5xl px-5 py-14">
        {!done ? (
          <div className="mx-auto max-w-2xl animate-rise text-center" key={step}>
            <div className="mb-8 flex justify-center gap-2">
              {STEPS.map((_, i) => <span key={i} className={cn("h-1.5 w-10 rounded-full", i <= step ? "bg-gold" : "bg-border")} />)}
            </div>
            <p className="eyebrow">Question {step + 1} of {STEPS.length}</p>
            <h2 className="mt-3 text-4xl">{STEPS[step].q}</h2>
            <div className="mt-10 grid gap-3 sm:grid-cols-2">
              {STEPS[step].options.map((o) => (
                <button key={o.v} onClick={() => { setAns({ ...ans, [STEPS[step].key]: o.v }); setStep(step + 1); }}
                  className="rounded-2xl border border-border bg-card px-6 py-5 font-display text-2xl capitalize shadow-soft transition hover:-translate-y-0.5 hover:border-gold">
                  {o.l}
                </button>
              ))}
            </div>
            {step > 0 && <button onClick={() => setStep(step - 1)} className="mt-8 text-sm text-muted-foreground hover:text-foreground">← Back</button>}
          </div>
        ) : (
          <div className="animate-rise">
            <div className="mx-auto max-w-2xl rounded-3xl bg-ink p-8 text-center text-ink-foreground">
              <Sparkles className="mx-auto h-6 w-6 text-gold" />
              <p className="mt-3 font-display text-3xl">{matchHeadline(answers)}</p>
              <p className="mt-3 text-xs uppercase tracking-widest text-ink-foreground/60">Recommendation generated by our rule-based matchmaker</p>
            </div>
            {results.length ? (
              <div className="mt-10 grid gap-6 sm:grid-cols-2 lg:grid-cols-3">
                {results.map((r) => <ProductCard key={r.product.id} product={r.product} note={`Why: it ${r.reasons.join(", ")}.`} />)}
              </div>
            ) : (
              <p className="mt-10 text-center text-muted-foreground">We couldn't find a close match in stock. <Link to="/shop" className="underline">Browse all candles</Link> or ask our Candle Concierge.</p>
            )}
            <div className="mt-10 text-center">
              <Button variant="outline" onClick={() => { setStep(0); setAns({}); }}>Start again</Button>
            </div>
          </div>
        )}
      </div>
    </>
  );
}
